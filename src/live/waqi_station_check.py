"""Map our 7 stations to WAQI (api.waqi.info) station ids, report each feed's last update, and sanity-check the gas readings.

WAQI's ``iaqi`` carries US-EPA sub-indices, not concentrations, so the only check available without a second live concentration
source is a plausibility one: convert the live sub-index back with ``src.live.epa_aqi`` and place it in last October's
10:00-12:00 distribution at the same station (``Og Data``). It cannot prove a unit or averaging convention; a systematic offset
(here: every gas at the bottom of its distribution) says the convention is not what ``epa_aqi`` assumes, or WAQI's gas inputs
are not the CPCB concentrations. Exact comparison needs a fresh concentration feed (OpenAQ is stale) and is logged as TODO.

The token is read from ``WAQI_API_TOKEN`` (env or ``.env``) and never printed.

    python -m src.live.waqi_station_check
"""

from __future__ import annotations

import json
import os
import urllib.request
from pathlib import Path

import pandas as pd

from src.features.build_features import load_caaqms_offline
from src.live.epa_aqi import from_aqi

REPO_ROOT = Path(__file__).resolve().parents[2]
OUT_DIR = REPO_ROOT / "docs" / "TIER_3"
BOUNDS = "28.40,76.80,28.95,77.45"
# our station -> WAQI uid, chosen by name and distance to the station coordinates in src/live/load_stations.py
MAPPING = {
    "Anand Vihar": (2553, "exact name"),
    "Bawana": (11267, "Pooth Khurd, Bawana; ~0.5 km"),
    "Dwarka-Sector 8": (10119, "NIMR, Sector 8, Dwarka; ~0.7 km"),
    "ITO": (
        10111,
        "NO ITO station on WAQI; nearest is Major Dhyan Chand National Stadium, ~1.9 km, a different monitor",
    ),
    "Jahangirpuri": (10113, "ITI Jahangirpuri; ~0.1 km"),
    "Punjabi Bagh": (2555, "exact name"),
    "R K Puram": (2556, "R.K. Puram"),
}
POLLUTANTS = ["pm25", "pm10", "no2", "so2", "co", "o3"]


def token() -> str:
    value = os.environ.get("WAQI_API_TOKEN")
    if not value and (REPO_ROOT / ".env").exists():
        for line in (REPO_ROOT / ".env").read_text().splitlines():
            if line.startswith("WAQI_API_TOKEN="):
                value = line.split("=", 1)[1].strip().strip("\"'")
    if not value:
        raise SystemExit("WAQI_API_TOKEN is not set (env var or .env)")
    return value


def get(path: str, key: str) -> dict:
    sep = "&" if "?" in path else "?"
    with urllib.request.urlopen(f"https://api.waqi.info{path}{sep}token={key}", timeout=30) as response:
        return json.load(response)


def main() -> None:
    key = token()
    now = pd.Timestamp.now(tz="Asia/Kolkata")
    feeds = {name: get(f"/feed/@{uid}/", key)["data"] for name, (uid, _) in MAPPING.items()}
    history = load_caaqms_offline(
        pd.Timestamp("2025-10-01", tz="Asia/Kolkata"), pd.Timestamp("2025-10-31 23:00", tz="Asia/Kolkata")
    )
    history = history[history.timestamp.dt.hour.isin([10, 11, 12])]

    stations, checks = [], []
    for name, data in feeds.items():
        stamp = pd.Timestamp(data["time"]["iso"])
        stations.append(
            {
                "station": name,
                "waqi_uid": data["idx"],
                "waqi_name": data["city"]["name"],
                "match": MAPPING[name][1],
                "last_update_ist": stamp.tz_convert("Asia/Kolkata").strftime("%Y-%m-%d %H:%M"),
                "age_min": round((now - stamp).total_seconds() / 60),
                "agencies": "; ".join(
                    a["name"] for a in data.get("attributions", []) if a["name"] != "World Air Quality Index Project"
                ),
                "has_weather": all(k in data["iaqi"] for k in ("t", "h", "w")),
            }
        )
        past = history[history.station_name == name]
        for pollutant in POLLUTANTS:
            if pollutant not in data["iaqi"]:
                continue
            sub = float(data["iaqi"][pollutant]["v"])
            live = float(from_aqi(pollutant, [sub])[0])
            reference = past[pollutant].dropna()
            checks.append(
                {
                    "station": name,
                    "pollutant": pollutant,
                    "iaqi": sub,
                    "backconverted": round(live, 2),
                    "oct2025_p10": round(reference.quantile(0.1), 2),
                    "oct2025_p50": round(reference.median(), 2),
                    "oct2025_p90": round(reference.quantile(0.9), 2),
                    "percentile_in_oct2025": round((reference < live).mean() * 100),
                }
            )
    st, ck = pd.DataFrame(stations), pd.DataFrame(checks)
    st.to_csv(OUT_DIR / "waqi_stations.csv", index=False)
    ck.to_csv(OUT_DIR / "waqi_plausibility.csv", index=False)
    medians = ck.groupby("pollutant").percentile_in_oct2025.median().reindex(POLLUTANTS)
    lines = [
        "# WAQI station mapping and plausibility check",
        "",
        f"Generated by `src/live/waqi_station_check.py` at {now:%Y-%m-%d %H:%M} IST; numbers come from `waqi_stations.csv` and `waqi_plausibility.csv`.",
        "",
        "Feed times are IST (`time.iso`, +05:30). The `/map/bounds` endpoint labels the same times `+09:00`; ignore that label.",
        "",
        "| Our station | WAQI uid | WAQI name | Match | Last update (IST) | Age (min) | Originating agency | Weather in feed |",
        "| :--- | ---: | :--- | :--- | :--- | ---: | :--- | :---: |",
    ]
    lines += [
        f"| {r.station} | {r.waqi_uid} | {r.waqi_name} | {r.match} | {r.last_update_ist} | {r.age_min} | {r.agencies} | {'yes' if r.has_weather else 'no'} |"
        for r in st.itertuples()
    ]
    lines += [
        "",
        "## Gas readings versus last October at the same station and hours (10:00-12:00 IST)",
        "",
        "`iaqi` converted back with `src/live/epa_aqi.py`, then placed in the October 2025 10-12h distribution of the CPCB concentrations. "
        "A percentile near 50 is typical; near 0 means below nearly every October reading.",
        "",
        "| Pollutant | Median percentile over 7 stations |",
        "| :--- | ---: |",
    ]
    lines += [f"| {p} | {v:.0f} |" for p, v in medians.items()]
    lines += [
        "",
        "| Station | Pollutant | iaqi | Back-converted | Oct p10 | Oct p50 | Oct p90 | Percentile |",
        "| :--- | :--- | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    lines += [
        f"| {r.station} | {r.pollutant} | {r.iaqi} | {r.backconverted} | {r.oct2025_p10} | {r.oct2025_p50} | {r.oct2025_p90} | {r.percentile_in_oct2025} |"
        for r in ck.itertuples()
    ]
    lines += [
        "",
        "Caveats: one hour on one day against a month a year earlier; units are ug/m3 (CO mg/m3); no concentration source is fresh, so no same-hour comparison.",
        "TODO: log WAQI vs OpenAQ on overlapping hours once OpenAQ is fresh; confirm WAQI's reference temperature and CO/O3 averaging against it.",
    ]
    (OUT_DIR / "waqi_stations.md").write_text("\n".join(lines) + "\n")
    print(st.to_string(index=False))
    print(medians.to_string())


if __name__ == "__main__":
    main()
